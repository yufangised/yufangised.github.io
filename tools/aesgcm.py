RCON = [0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36,0x6c,0xd8,0xab,0x4d]


def _xtime(a):
    a <<= 1
    if a & 0x100:
        a = (a ^ 0x1b) & 0xff
    return a


def _mul(a, b):
    """GF(2^8) 乘法，用于 MixColumns。"""
    r = 0
    for _ in range(8):
        if b & 1:
            r ^= a
        b >>= 1
        a = _xtime(a)
    return r


def expand_key(key):
    """AES-256 密钥扩展 -> 15 个轮密钥，每个 16 字节。"""
    assert len(key) == 32
    nk, nr = 8, 14
    w = [list(key[4 * i:4 * i + 4]) for i in range(nk)]
    for i in range(nk, 4 * (nr + 1)):
        t = list(w[i - 1])
        if i % nk == 0:
            t = t[1:] + t[:1]
            t = [SBOX[x] for x in t]
            t[0] ^= RCON[i // nk - 1]
        elif i % nk == 4:
            t = [SBOX[x] for x in t]
        w.append([w[i - nk][j] ^ t[j] for j in range(4)])
    return [bytes(b for word in w[4 * r:4 * r + 4] for b in word) for r in range(nr + 1)]


def encrypt_block(rk, block):
    """正向 AES 单块加密。state 按列主序，与 FIPS-197 一致。"""
    s = [block[i] ^ rk[0][i] for i in range(16)]
    nr = len(rk) - 1
    for rnd in range(1, nr + 1):
        s = [SBOX[x] for x in s]
        # ShiftRows：state[r][c] 位于 s[r + 4c]
        s = [s[(i + 4 * (i % 4)) % 16] for i in range(16)]
        if rnd != nr:
            ns = []
            for c in range(4):
                col = s[4 * c:4 * c + 4]
                ns += [
                    _mul(col[0], 2) ^ _mul(col[1], 3) ^ col[2] ^ col[3],
                    col[0] ^ _mul(col[1], 2) ^ _mul(col[2], 3) ^ col[3],
                    col[0] ^ col[1] ^ _mul(col[2], 2) ^ _mul(col[3], 3),
                    _mul(col[0], 3) ^ col[1] ^ col[2] ^ _mul(col[3], 2),
                ]
            s = ns
        s = [s[i] ^ rk[rnd][i] for i in range(16)]
    return bytes(s)


# ── GHASH ──────────────────────────────────────────────────────────────
R = 0xe1 << 120


def _gmul(x, y):
    """GF(2^128) 乘法，GCM 的位序（最高位在前）。"""
    z, v = 0, y
    for i in range(128):
        if x & (1 << (127 - i)):
            z ^= v
        if v & 1:
            v = (v >> 1) ^ R
        else:
            v >>= 1
    return z


def _ghash(h, data):
    y = 0
    for i in range(0, len(data), 16):
        blk = data[i:i + 16].ljust(16, b'\x00')
        y = _gmul(y ^ int.from_bytes(blk, 'big'), h)
    return y.to_bytes(16, 'big')


def _inc32(block):
    pre, ctr = block[:12], int.from_bytes(block[12:], 'big')
    return pre + ((ctr + 1) & 0xffffffff).to_bytes(4, 'big')


def _gctr(rk, icb, data):
    if not data:
        return b''
    out, cb = bytearray(), icb
    for i in range(0, len(data), 16):
        ks = encrypt_block(rk, cb)
        chunk = data[i:i + 16]
        out += bytes(a ^ b for a, b in zip(chunk, ks))
        cb = _inc32(cb)
    return bytes(out)


def _j0(rk, h, iv):
    """IV 为 96 位时直接拼接；否则（本例 128 位）走 GHASH 推导。"""
    if len(iv) == 12:
        return iv + b'\x00\x00\x00\x01'
    pad = (-len(iv)) % 16
    return _ghash(h, iv + b'\x00' * pad + b'\x00' * 8 + (len(iv) * 8).to_bytes(8, 'big'))


def _tag(rk, h, j0, aad, ct):
    data = (aad + b'\x00' * ((-len(aad)) % 16) +
            ct + b'\x00' * ((-len(ct)) % 16) +
            (len(aad) * 8).to_bytes(8, 'big') + (len(ct) * 8).to_bytes(8, 'big'))
    s = _ghash(h, data)
    return _gctr(rk, j0, s)


def decrypt(key, iv, ct, tag, aad=b''):
    """返回明文；认证失败抛 ValueError。"""
    rk = expand_key(key)
    h = int.from_bytes(encrypt_block(rk, b'\x00' * 16), 'big')
    j0 = _j0(rk, h, iv)
    pt = _gctr(rk, _inc32(j0), ct)
    if _tag(rk, h, j0, aad, ct) != tag:
        raise ValueError('认证失败')
    return pt


def encrypt(key, iv, pt, aad=b''):
    """返回 (密文, tag)。"""
    rk = expand_key(key)
    h = int.from_bytes(encrypt_block(rk, b'\x00' * 16), 'big')
    j0 = _j0(rk, h, iv)
    ct = _gctr(rk, _inc32(j0), pt)
    return ct, _tag(rk, h, j0, aad, ct)
